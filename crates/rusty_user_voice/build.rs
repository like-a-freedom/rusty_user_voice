//! Build script for the `rusty_user_voice` crate.
//!
//! Walks the `skills/` directory next to the manifest and generates a table
//! of `(relative path, content)` pairs in `OUT_DIR`. `src/skills.rs` includes
//! that table, so the agent-facing corpus is compiled into the binary and
//! always matches the installed version.
//!
//! The corpus lives inside the crate rather than above it on purpose: an
//! `include_str!` that reaches outside the package root compiles under
//! `cargo build` and `cargo install --path`, but it breaks `cargo package`,
//! because the packaged tarball omits the out-of-package file.
//!
//! The layout is validated here, at build time. A file that is neither
//! `<skill>/SKILL.md` nor `<skill>/references/*.md` fails the build, where
//! the mistake is cheap to fix and the message can name the file. Letting it
//! through would put a stray file into the binary, where it would crash
//! `skills list` for every user of the installed binary.

use std::{
    env, fs,
    path::{Path, PathBuf},
};

fn main() {
    let manifest_dir =
        PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is set by cargo"));
    let skills_dir = manifest_dir.join("skills");

    if !skills_dir.is_dir() {
        panic!(
            "skill corpus directory is missing: {}\n\
             The corpus is compiled into the binary; see docs/agents/skills.md.",
            skills_dir.display()
        );
    }

    // Watch the directory, not just the files. Emitting a path disables
    // cargo's default "rerun on any change in the package", so without this
    // line a newly added reference would not trigger a rebuild and would
    // silently not be served.
    println!("cargo:rerun-if-changed={}", skills_dir.display());

    let mut files = Vec::new();
    collect(&skills_dir, &skills_dir, &mut files);
    files.sort_by(|left, right| left.0.cmp(&right.0));
    validate(&files, &skills_dir);

    let mut generated = String::from(
        "// @generated by build.rs. Do not edit.\n\
         pub const SKILL_FILES: &[(&str, &str)] = &[\n",
    );
    for (relative, _) in &files {
        // `CARGO_MANIFEST_DIR` keeps the generated source machine-independent,
        // so the build cache survives a move of the checkout. `include_str!`
        // takes the macro call itself, not a quoted string.
        let include = format!(
            "concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/skills/{}\")",
            relative.replace('\\', "/")
        );
        generated.push_str(&format!("    ({relative:?}, include_str!({include})),\n"));

        let absolute = skills_dir.join(relative);
        println!("cargo:rerun-if-changed={}", absolute.display());
    }
    generated.push_str("];\n");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR is set by cargo"));
    fs::write(out_dir.join("skill_files.rs"), generated)
        .expect("write the generated skill file table");
}

/// Collect every corpus file, keyed by its path relative to the corpus root.
///
/// The corpus layout is `<skill>/SKILL.md` plus `<skill>/references/*.md`.
/// Anything else is a mistake, and it fails the build here rather than
/// becoming a runtime panic.
fn collect(root: &Path, directory: &Path, files: &mut Vec<(String, PathBuf)>) {
    let entries = fs::read_dir(directory)
        .unwrap_or_else(|error| panic!("read {}: {error}", directory.display()));
    for entry in entries {
        let entry = entry.unwrap_or_else(|error| panic!("read entry: {error}"));
        let path = entry.path();
        let relative = path
            .strip_prefix(root)
            .expect("path is under the corpus root")
            .to_string_lossy()
            .replace('\\', "/");

        if path.is_dir() {
            if relative == "references" {
                panic!(
                    "the corpus has a top-level 'references' directory: {}\n\
                     References belong to a skill: <skill>/references/<name>.md.",
                    path.display()
                );
            }
            collect(root, &path, files);
            continue;
        }

        if !is_corpus_file(&relative) {
            panic!(
                "the corpus holds a file that is not part of a skill: {}\n\
                 Expected <skill>/SKILL.md or <skill>/references/<name>.md.\n\
                 See docs/agents/skills.md.",
                path.display()
            );
        }

        files.push((relative, path));
    }
}

/// Whether a corpus-relative path is a file the corpus may hold.
fn is_corpus_file(relative: &str) -> bool {
    let mut parts = relative.split('/');
    let Some(skill) = parts.next() else {
        return false;
    };
    if skill.is_empty() {
        return false;
    }
    match parts.next() {
        Some("SKILL.md") => parts.next().is_none(),
        Some("references") => {
            matches!(parts.next(), Some(name) if !name.is_empty() && parts.next().is_none())
        }
        _ => false,
    }
}

/// Every skill directory has to hold a `SKILL.md`.
///
/// A directory with only references would otherwise vanish without a word:
/// the runtime builds the catalog from the documents, so a skill without one
/// is invisible.
fn validate(files: &[(String, PathBuf)], skills_dir: &Path) {
    let mut skills: Vec<&str> = files
        .iter()
        .filter_map(|(relative, _)| relative.split('/').next())
        .collect();
    skills.sort_unstable();
    skills.dedup();

    for skill in skills {
        let document = format!("{skill}/SKILL.md");
        if !files.iter().any(|(relative, _)| *relative == document) {
            panic!(
                "the corpus skill '{skill}' has no SKILL.md: {}\n\
                 Every skill needs a document; the references of a skill sit in \
                 <skill>/references/. See docs/agents/skills.md.",
                skills_dir.join(skill).display()
            );
        }
    }
}
