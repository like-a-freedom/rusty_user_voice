//! The agent-facing corpus compiled into the binary.
//!
//! `build.rs` walks the `skills/` directory next to the crate manifest and
//! generates a table of every corpus file. This module turns that flat table
//! into a catalog of skills and their references.
//!
//! The corpus lives inside the crate so the instructions an agent reads
//! always match the installed binary. See `docs/agents/skills.md` for the
//! contract that keeps the two in step.

use std::collections::BTreeMap;

use serde::Deserialize;

/// Frontmatter of a skill document.
#[derive(Debug, Deserialize)]
struct Frontmatter {
    name: String,
    description: String,
}

/// One reference document belonging to a skill.
#[derive(Debug)]
pub struct Reference {
    /// Path of the reference relative to the skill directory.
    pub path: String,
    /// File name of the reference, for example `cli.md`.
    pub name: String,
    /// The reference text.
    pub content: &'static str,
}

/// One bundled skill.
#[derive(Debug)]
pub struct Skill {
    /// Path of the skill document inside the corpus, for example
    /// `core/SKILL.md`.
    pub path: &'static str,
    /// Skill name, taken from the frontmatter.
    pub name: String,
    /// One-line summary, taken from the frontmatter.
    pub description: String,
    /// The `SKILL.md` document, frontmatter included.
    pub content: &'static str,
    /// The references the skill owns.
    pub references: Vec<Reference>,
}

/// The corpus files, generated by `build.rs`.
mod generated {
    include!(concat!(env!("OUT_DIR"), "/skill_files.rs"));
}

impl Skill {
    /// Find a reference by file name (`cli.md`) or by path
    /// (`references/cli.md`).
    pub fn reference(&self, query: &str) -> Option<&Reference> {
        let query = query.trim();
        self.references
            .iter()
            .find(|reference| reference.name == query || reference.path == query)
    }
}

/// Every bundled skill, ordered by name.
pub fn catalog() -> Vec<Skill> {
    let mut documents: BTreeMap<&str, (&'static str, &'static str)> = BTreeMap::new();
    let mut references: BTreeMap<&str, Vec<Reference>> = BTreeMap::new();

    for (path, content) in generated::SKILL_FILES {
        let (skill, file) = path
            .split_once('/')
            .expect("every corpus file lives in a skill directory");
        if file == "SKILL.md" {
            documents.insert(skill, (path, content));
            continue;
        }
        let name = file
            .strip_prefix("references/")
            .expect("every file next to SKILL.md is a reference");
        references.entry(skill).or_default().push(Reference {
            path: file.to_owned(),
            name: name.to_owned(),
            content,
        });
    }

    documents
        .into_iter()
        .map(|(directory, (path, content))| {
            let frontmatter = parse_frontmatter(content);
            Skill {
                path,
                name: frontmatter.name,
                description: frontmatter.description,
                content,
                references: references.remove(directory).unwrap_or_default(),
            }
        })
        .collect()
}

/// Find one skill by name.
pub fn find(name: &str) -> Option<Skill> {
    catalog()
        .into_iter()
        .find(|skill| skill.name.eq_ignore_ascii_case(name.trim()))
}

/// Read the frontmatter of a skill document.
fn parse_frontmatter(content: &'static str) -> Frontmatter {
    let rest = content
        .strip_prefix("---\n")
        .expect("every skill document opens with frontmatter");
    let end = rest
        .find("\n---\n")
        .expect("every skill document closes its frontmatter");
    serde_yaml::from_str(&rest[..end]).expect("every skill frontmatter is valid YAML")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn catalog_holds_the_expected_skills() {
        let names: Vec<String> = catalog().into_iter().map(|skill| skill.name).collect();
        assert_eq!(names, vec!["core", "feedback-loop", "triage"]);
    }

    #[test]
    fn every_skill_has_a_description_and_a_document() {
        for skill in catalog() {
            assert!(
                !skill.description.trim().is_empty(),
                "{} has no description",
                skill.name
            );
            assert!(
                skill.content.starts_with("---\n"),
                "{} must keep its frontmatter",
                skill.name
            );
        }
    }

    #[test]
    fn core_owns_every_reference_and_mentions_it() {
        let core = find("core").expect("core is bundled");
        let names: Vec<&str> = core
            .references
            .iter()
            .map(|reference| reference.name.as_str())
            .collect();
        assert_eq!(
            names,
            vec![
                "cli.md",
                "envelope.md",
                "errors.md",
                "mcp-tools.md",
                "pagination.md"
            ]
        );
        for reference in &core.references {
            assert!(
                core.content.contains(&reference.name),
                "core does not link {}",
                reference.name
            );
        }
    }

    #[test]
    fn a_reference_resolves_by_name_and_by_path() {
        let core = find("core").expect("core is bundled");
        assert_eq!(
            core.reference("cli.md")
                .map(|reference| reference.name.as_str()),
            Some("cli.md")
        );
        assert_eq!(
            core.reference("references/cli.md")
                .map(|reference| reference.name.as_str()),
            Some("cli.md")
        );
        assert!(core.reference("nope.md").is_none());
    }

    #[test]
    fn an_unknown_skill_is_not_found() {
        assert!(find("nope").is_none());
    }
}
